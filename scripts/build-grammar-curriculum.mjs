import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const source = readFileSync(`${root}supabase/seeds/grammar-curriculum-2026.txt`, 'utf8')
const levels = ['A1.1', 'A1.2', 'A2.1', 'A2.2', 'B1.1', 'B1.2']
const records = []
let group
let exerciseNumber = 0
const lessonNumbers = new Map()
for (const raw of source.split('\n')) {
  const line = raw.trim()
  if (!line || line.startsWith('#')) continue
  if (line.startsWith('@ ')) {
    const [level, topic, hint] = line.slice(2).split('|').map(value => value.trim())
    const lesson = (lessonNumbers.get(level) ?? 0) + 1
    lessonNumbers.set(level, lesson)
    group = { level, topic, hint, lesson }
    exerciseNumber = 0
    continue
  }
  if (!group) throw new Error('Missing topic heading')
  const [sentence, firstDistractor, secondDistractor, instruction] = line.split('|').map(value => value.trim())
  const distractors = [firstDistractor, secondDistractor]
  const match = sentence.match(/^(.*?)\[([^\]]+)\](.*)$/)
  if (!match || sentence.match(/\[/g)?.length !== 1) throw new Error(`Invalid blank: ${sentence}`)
  exerciseNumber += 1
  const [, before, answer, after] = match
  const options = [...distractors]
  options.splice(exerciseNumber % (options.length + 1), 0, answer)
  if (new Set(options.map(option => option.toLocaleLowerCase('de-DE'))).size !== 3) {
    throw new Error(`Duplicate or missing options: ${sentence}`)
  }
  const hex = createHash('sha256').update(`sitov-grammar-2026:${group.level}:${group.lesson}:${exerciseNumber}`).digest('hex')
  const id = `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`
  const choice = exerciseNumber % 5 === 0
  records.push({
    id,
    level: group.level,
    lesson: `${group.level} · ${String(group.lesson).padStart(2, '0')}`,
    topic: group.topic,
    type: choice ? 'multiple_choice' : 'fill_in_blank',
    content: choice
      ? { question: `${before}___${after}`, options, correct_answer: answer, explanation: group.hint, ...(instruction ? { instruction } : {}) }
      : { text_before: before, text_after: after, correct_answer: answer, options, smart_hint: group.hint, ...(instruction ? { instruction } : {}) },
    hint_ru: null,
    hint_tr: null,
    solution_audio_url: null,
  })
}
for (const level of levels) {
  const count = records.filter(row => row.level === level).length
  if (count !== 100) throw new Error(`${level} has ${count}, expected 100`)
}
if (new Set(records.map(row => row.id)).size !== 600) throw new Error('Duplicate identifiers')
writeFileSync(`${root}supabase/seeds/grammar-curriculum-2026.json`, `${JSON.stringify(records, null, 2)}\n`)
const quote = value => value === null ? 'NULL' : `'${value.replaceAll("'", "''")}'`
const values = records.map(row => `(${[row.id, row.level, row.lesson, row.topic, row.type, JSON.stringify(row.content), null, null, null].map(quote).join(', ')})`)
writeFileSync(`${root}supabase/seeds/grammar-curriculum-2026.sql`, `-- Generated by scripts/build-grammar-curriculum.mjs; 600 original exercises.\n-- Stable IDs + DO NOTHING preserve teacher edits and all existing progress.\nINSERT INTO public.exercises (id, level, lesson, topic, type, content, hint_ru, hint_tr, solution_audio_url) VALUES\n${values.join(',\n')}\nON CONFLICT (id) DO NOTHING;\n`)
console.log(`Validated and generated ${records.length} grammar exercises (${levels.join(', ')}: 100 each).`)
