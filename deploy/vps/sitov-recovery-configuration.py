#!/usr/bin/env python3
"""Private recovery settings for a daily encrypted Sitov Academy backup.

Capture only configuration, never source checkouts, database data or Storage.
The caller holds the daily-backup lock. No credentials or file contents are
printed; this module does not alter any live configuration.
"""
import hashlib
import io
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import tarfile

SERVICE = '/data/coolify/services/eknmzxvqilojjicinatnllbt'
DB = 'supabase-db-eknmzxvqilojjicinatnllbt'
MAX_BYTES = 64 * 1024 ** 2
MAX_FILES = 4096
ARCHIVE = 'sitov-configuration.tar'


def database_state():
    result = subprocess.run(['docker', 'inspect', DB], check=True,
                            capture_output=True, text=True)
    value = json.loads(result.stdout)[0]
    mounts = [m for m in value['Mounts'] if m['Destination'] == '/etc/postgresql-custom']
    if len(mounts) != 1 or mounts[0]['Type'] != 'volume':
        raise ValueError('Active PostgreSQL configuration volume unavailable')
    source = Path(mounts[0]['Source'])
    if not source.is_absolute() or source.name != '_data' or source.parent.parent != Path('/var/lib/docker/volumes'):
        raise ValueError('Unexpected PostgreSQL configuration volume')
    # These values stay inside the encrypted configuration archive. Include the
    # actual DB environment as well as Compose, and detect image/container/key
    # changes while the logical dump and Storage export are being produced.
    return {'container_id': value['Id'], 'image': value['Image'],
            'environment': value['Config']['Env'], 'postgres_custom': str(source)}


def scoped_sources(root, db_state):
    def host(path):
        return root / path.lstrip('/')
    required = [host('/etc/sitov-academy/app.env'), host('/etc/nginx/nginx.conf'),
                host('/etc/systemd/system/sitov-app.service'),
                host('/etc/systemd/system/sitov-mail.service'),
                host(SERVICE + '/docker-compose.yml'), host(SERVICE + '/.env'),
                host(db_state['postgres_custom'] + '/pgsodium_root.key')]
    sources = [host(p) for p in ('/etc/sitov-academy', '/etc/nginx', '/etc/letsencrypt',
                                '/etc/docker/daemon.json', '/etc/ufw',
                                '/data/coolify/proxy/acme.json', '/data/coolify/proxy/certs',
                                '/data/coolify/proxy/dynamic', '/data/coolify/proxy/docker-compose.yml',
                                SERVICE + '/docker-compose.yml', SERVICE + '/.env',
                                SERVICE + '/entrypoint.sh', SERVICE + '/volumes/db',
                                SERVICE + '/volumes/api', SERVICE + '/volumes/pooler',
                                SERVICE + '/volumes/logs', db_state['postgres_custom'],
                                '/var/www/sitov-current/.sitov-runtime.env')]
    sources += sorted(host('/etc/systemd/system').glob('sitov-*'))
    sources += sorted(host('/etc/sysctl.d').glob('*sitov*'))
    # These are the actual small installed service helpers, not Git checkouts
    # or generated bytecode. They are needed to restore the saved ExecStart jobs.
    for extension in ('*.py', '*.sh'):
        sources += sorted(host('/opt/sitov-ops').glob(extension))
    postfix = host('/etc/postfix/main.cf')
    if postfix.is_file() and not postfix.is_symlink():
        required += [postfix, host('/etc/postfix/master.cf')]
        sources += [postfix, host('/etc/postfix/master.cf'),
                    host('/etc/systemd/system/postfix@-.service.d'),
                    host('/etc/default/postfix')]
        # A broad /etc/postfix copy follows package-maintained binary links.
        # Only actual configured maps and TLS files are recovery settings.
        text = postfix.read_text()
        maps = set(re.findall(r'(?:hash|lmdb|btree|texthash|regexp|pcre|cidr):(/[^,\s#]+)', text))
        maps.add('/etc/aliases')  # Ubuntu's active default alias map.
        files = set(maps)
        for path in maps:
            for suffix in ('.db', '.lmdb'):
                if host(path + suffix).exists():
                    files.add(path + suffix)
        files.update(re.findall(r'^\s*smtpd?_tls_(?:cert|key)_file\s*=\s*(/\S+)', text, re.M))
        for path in sorted(files):
            if not path.startswith('/etc/') or '..' in Path(path).parts:
                raise ValueError('Unexpected mail recovery configuration path')
            sources.append(host(path))
            required.append(host(path))
    dkim = host('/etc/opendkim.conf')
    if dkim.is_file() and not dkim.is_symlink():
        sources += [dkim, host('/etc/opendkim'), host('/etc/default/opendkim'),
                    host('/etc/systemd/system/opendkim.service.d')]
        required.append(dkim)
        for path in re.findall(r'^\s*KeyFile\s+(/\S+)', dkim.read_text(), re.M):
            if not path.startswith('/etc/opendkim/') or '..' in Path(path).parts:
                raise ValueError('Unexpected DKIM recovery key path')
            required.append(host(path))
    return sorted(set(sources)), required


class ConfigurationSnapshot:
    def __init__(self, root, reader, state, entries):
        self.root, self.reader, self.state, self.entries = root, reader, state, entries
        self.source_bytes = sum(len(value['data']) for value in entries.values()) + len(json.dumps(state).encode())
        # Tar metadata, padding and the inventory are also included in the disk
        # estimate. The existing 20-GiB operating reserve remains additional.
        self.estimated_bytes = self.source_bytes + len(entries) * 4096 + 10240

    def assert_unchanged(self):
        current = capture_configuration(self.root, self.reader)
        if self.state != current.state or self.entries != current.entries:
            raise RuntimeError('Recovery configuration changed during backup; keeping the prior recovery point')

    def write(self, target):
        output = target / ARCHIVE
        if output.exists() or output.is_symlink():
            raise ValueError('Recovery configuration archive already exists')
        inventory = {'format': 1, 'restore_paths': 'relative to filesystem root',
                     'database': self.state, 'files': {name: {
                         key: value for key, value in entry.items() if key != 'data'
                     } for name, entry in self.entries.items()}}
        with output.open('xb') as stream:
            with tarfile.open(fileobj=stream, mode='w', format=tarfile.PAX_FORMAT) as archive:
                for name, entry in self.entries.items():
                    info = tarfile.TarInfo(name)
                    info.mode, info.uid, info.gid = entry['mode'], entry['uid'], entry['gid']
                    if entry['kind'] == 'symlink':
                        info.type, info.linkname = tarfile.SYMTYPE, entry['link']
                        archive.addfile(info)
                    else:
                        info.size = len(entry['data'])
                        archive.addfile(info, io.BytesIO(entry['data']))
                metadata = json.dumps(inventory, sort_keys=True, indent=2).encode() + b'\n'
                info = tarfile.TarInfo('sitov-recovery-configuration.json')
                info.mode, info.size = 0o600, len(metadata)
                archive.addfile(info, io.BytesIO(metadata))
            stream.flush()
            os.fsync(stream.fileno())
        output.chmod(0o600)
        hashes_path = target / 'sha256.json'
        hashes = json.loads(hashes_path.read_text())
        if not isinstance(hashes, dict) or ARCHIVE in hashes:
            raise ValueError('Invalid logical backup manifest')
        hashes[ARCHIVE] = hashlib.sha256(output.read_bytes()).hexdigest()
        hashes_path.write_text(json.dumps(hashes, indent=2) + '\n')
        return output


def capture_configuration(root=Path('/'), state_reader=database_state):
    root = root.resolve()
    state_data = json.dumps(state_reader(), sort_keys=True).encode()
    if len(state_data) > 1024 ** 2:
        raise ValueError('Database recovery configuration exceeds the size limit')
    state = json.loads(state_data)
    sources, required = scoped_sources(root, state)
    for path in required:
        if path.is_symlink() or not path.is_file() or path.stat().st_size == 0:
            raise ValueError('A required recovery configuration file is unavailable')
    existing = [p for p in sources if p.exists() or p.is_symlink()]
    for path in existing:
        if path.is_symlink():
            raise ValueError('A recovery configuration root must not be a symlink')
    allowed = [p.resolve() for p in existing]
    entries, total = {}, 0

    def include(path):
        nonlocal total
        name = path.relative_to(root).as_posix()
        before = path.lstat()
        if stat.S_ISDIR(before.st_mode):
            for child in sorted(path.iterdir()):
                include(child)
            return
        if name in entries:
            return
        if len(entries) >= MAX_FILES:
            raise ValueError('Too many recovery configuration files')
        base = {'mode': stat.S_IMODE(before.st_mode), 'uid': before.st_uid, 'gid': before.st_gid}
        if stat.S_ISLNK(before.st_mode):
            link = os.readlink(path)
            resolved = path.resolve(strict=True)
            if not any(resolved == p or resolved.is_relative_to(p) for p in allowed):
                raise ValueError('Recovery configuration link leaves its declared scope')
            # Store links only when their target is itself part of the snapshot.
            # The inode/path hash detects retargeting before or after the dump.
            entries[name] = dict(base, kind='symlink', link=link, data=b'',
                                 sha256=hashlib.sha256(link.encode()).hexdigest())
        elif stat.S_ISREG(before.st_mode):
            if before.st_size > MAX_BYTES - total:
                raise ValueError('Recovery configuration exceeds the size limit')
            data = path.read_bytes()
            after = path.lstat()
            if (before.st_dev, before.st_ino, before.st_size, before.st_mtime_ns, before.st_ctime_ns) != (
                    after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns):
                raise RuntimeError('Recovery configuration changed while reading it')
            total += len(data)
            if total > MAX_BYTES:
                raise ValueError('Recovery configuration exceeds the size limit')
            entries[name] = dict(base, kind='file', data=data, sha256=hashlib.sha256(data).hexdigest(),
                                 resolved_source=str(path.resolve()))
        else:
            raise ValueError('Recovery configuration contains a special file')

    for source in existing:
        include(source)
    return ConfigurationSnapshot(root, state_reader, state, dict(sorted(entries.items())))
