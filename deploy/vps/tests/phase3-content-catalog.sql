-- Read-only production/clone acceptance for Phase 3.4–3.5.
BEGIN READ ONLY;
SET LOCAL statement_timeout = '10s';
DO $verify$
DECLARE sample text; signature regprocedure;
BEGIN
 IF enum_range(NULL::public.learning_content_status)::text[] <> ARRAY['incomplete','ready'] THEN
  RAISE EXCEPTION 'Unexpected publication statuses';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_attribute WHERE attrelid='public.learning_exercises'::regclass
  AND attname='content_status' AND attgenerated='s') THEN
  RAISE EXCEPTION 'Publication status must be generated by PostgreSQL';
 END IF;
 IF EXISTS(SELECT 1 FROM public.learning_exercises WHERE (content_status='ready') IS DISTINCT FROM
  grammar_private.exercise_is_ready(content,topic)) THEN
  RAISE EXCEPTION 'Publication status is inconsistent';
 END IF;
 IF NOT grammar_private.valid_target_form('{"target_form":["heißen"]}')
  OR grammar_private.valid_target_form('{}') OR grammar_private.valid_target_form('{"target_form":[]}')
  OR grammar_private.valid_target_form('{"target_form":[" "]}') OR grammar_private.valid_target_form('{"target_form":[null]}') THEN
  RAISE EXCEPTION 'Target form validation failed';
 END IF;
 FOREACH sample IN ARRAY ARRAY['Привет','Їжак','ı','ğ','ş','İ','Ğ','Ş',U&'s\0327',U&'\+01E030'] LOOP
  IF learning_private.german_text_allowed(sample) THEN RAISE EXCEPTION 'Forbidden text accepted'; END IF;
 END LOOP;
 IF NOT learning_private.german_text_allowed('Äpfel, Öl, Grüße: Wie heißen Sie?') THEN
  RAISE EXCEPTION 'Valid German rejected';
 END IF;
 IF (SELECT count(*) FROM pg_trigger WHERE NOT tgisinternal AND tgenabled='O'
  AND (tgrelid='public.learning_exercises'::regclass AND tgname='guard_exercise_quality'
   OR tgrelid='public.learning_reading_texts'::regclass AND tgname='guard_reading_quality'))<>2 THEN
  RAISE EXCEPTION 'Missing enabled content guards';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='learning_exercises'
  AND policyname='released_content_read' AND qual LIKE '%content_status%ready%') THEN
  RAISE EXCEPTION 'Missing learner publication gate';
 END IF;
 IF NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public'
  AND table_name='grammar_translations' AND column_name='prompt' AND data_type='text') THEN
  RAISE EXCEPTION 'Missing normalized translation prompt';
 END IF;
 IF NOT has_schema_privilege('service_role','grammar_private','USAGE')
  OR has_schema_privilege('anon','grammar_private','USAGE') THEN
  RAISE EXCEPTION 'Unexpected content helper schema permissions';
 END IF;
 signature:='grammar_private.record_attempt(uuid,text,boolean)'::regprocedure;
 IF NOT EXISTS(SELECT 1 FROM pg_proc WHERE oid=signature AND prosecdef AND proconfig @> ARRAY['search_path=""'])
  OR strpos(pg_get_functiondef(signature),'phase3-content-ready-guard-v1')=0 THEN
  RAISE EXCEPTION 'Authoritative grader lacks publication guard';
 END IF;
 IF strpos(pg_get_functiondef('public.save_learning_content(text,jsonb,uuid)'::regprocedure),'phase3-content-quality-errors-v1')=0 THEN
  RAISE EXCEPTION 'CMS lacks explicit content errors';
 END IF;
END $verify$;
SELECT content_status,count(*) FROM public.learning_exercises GROUP BY content_status ORDER BY content_status;
SELECT 'Phase 3.4–3.5 content, publication, trigger and RPC catalog verified' AS result;
ROLLBACK;
