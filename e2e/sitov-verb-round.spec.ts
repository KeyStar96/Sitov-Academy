import { expect, test } from '@playwright/test'

test('a later-phase mistake resets to one and repeats the original task without another score', async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('sitov-intro-seen', '1')
    localStorage.setItem('sitov-consent', JSON.stringify({ version: 1, marketing: false, decidedAt: new Date().toISOString() }))
  })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/en/sitov-preview/verbs')
  await page.getByRole('button', { name: 'Open Box 3 · Familiar' }).click()
  await page.getByRole('button', { name: 'Practise this compartment' }).click()
  const form = page.locator('form[data-result]')
  await expect(form.getByRole('button', { name: 'Show solution' })).toBeVisible()
  const verb = await form.locator('h2').innerText()
  const parts = await form.locator('div[lang="de"] > span').allTextContents()
  await form.getByRole('button', { name: 'Show solution' }).click()
  const solution = await form.locator('[role="status"] b').innerText()
  await expect(page.getByRole('progressbar', { name: 'Your round' })).toHaveAttribute('aria-valuenow', '1')
  await form.getByRole('button', { name: 'Next form' }).click()
  await expect(form.getByText('Repeat', { exact: true })).toBeVisible()
  await expect(form.locator('h2')).toHaveText(verb)
  await form.getByRole('button', { name: 'Show solution' }).click()
  await form.getByRole('button', { name: 'Next form' }).click()
  const escaped = parts.map(part => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
  const answers = solution.match(new RegExp(`^${escaped.join('(.*?)')}$`))?.slice(1)
  expect(answers).toBeDefined()
  const inputs = await form.getByRole('textbox').all()
  expect(inputs).toHaveLength(answers!.length)
  for (let index = 0; index < inputs.length; index++) await inputs[index].fill(answers![index])
  await form.getByRole('button', { name: 'Check answer' }).click()
  await expect(form).toHaveAttribute('data-result', 'correct')
  await expect(page.getByRole('progressbar', { name: 'Your round' })).toHaveAttribute('aria-valuenow', '1')
  await form.getByRole('button', { name: 'End round' }).click()
  await expect(page.getByRole('heading', { name: 'One round further.' })).toBeVisible()
  await expect(page.locator('strong').filter({ hasText: '0 / 1' })).toBeVisible()
  await page.getByRole('button', { name: 'Back to verb trainer' }).click()
  await page.getByRole('button', { name: 'Open Box 1 · New' }).click()
  const card = page.getByRole('dialog').locator('li').filter({ has: page.locator('strong', { hasText: verb }) })
  await expect(card).toBeVisible()
  await expect(card.locator('[data-box="1"][data-due="false"]')).toHaveCount(1)
  await expect(card).toContainText('6 attempts')
  await expect(card).toContainText('4 correct')
})
