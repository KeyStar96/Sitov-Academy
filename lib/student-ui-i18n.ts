export const STUDENT_MESSAGES: Record<UiLocale, StudentMessages> = { de, en, ru, uk, tr }

export type StudentTranslator = (key: StudentMessageKey, variables?: TranslationVariables) => string

/**
 * Übersetzer mit Einzahl-Regel: Gibt es `<key>_one`, gilt er für genau 1.
 * Russisch und Ukrainisch sind so formuliert, dass die Zahl nie gebeugt wird.
 */
export function studentTranslator(lang: string): StudentTranslator & { count: (key: StudentMessageKey, count: number, variables?: TranslationVariables) => string } {
  const messages = STUDENT_MESSAGES[toUiLocale(lang)]
  const translate = ((key, variables) => interpolate(messages[key], variables)) as StudentTranslator
  return Object.assign(translate, {
    count(key: StudentMessageKey, count: number, variables?: TranslationVariables) {
      const singular = `${key}_one` as StudentMessageKey
      const template = count === 1 && singular in messages ? messages[singular] : messages[key]
      return interpolate(template, { count, ...variables })
    },
  })
}
