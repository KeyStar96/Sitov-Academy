-- Existing reset operations remove only the requested verb scope; selecting a
-- different level and removing a verb never call these reset operations.
DO $sitov$
DECLARE body text; marker text; signature text; replacement text;
BEGIN
 IF to_regprocedure('public.get_last_active_level()') IS NOT NULL THEN
  body:=pg_get_functiondef('public.get_last_active_level()'::regprocedure);
  IF strpos(body,'FROM public.sitov_verb_challenges')=0 THEN
   marker:='), latest AS (';
   IF strpos(body,marker)=0 THEN RAISE EXCEPTION 'sitov_verb_activity_contract_changed'; END IF;
   body:=replace(body,marker,$fragment$
   UNION ALL SELECT c.context_level,'verbs',p.last_answered_at,NULL::text,NULL::text
    FROM public.sitov_verb_progress p JOIN public.sitov_verb_catalog v ON v.id=p.verb_id
    JOIN LATERAL (SELECT ch.context_level FROM public.sitov_verb_challenges ch WHERE ch.auth_user_id=p.auth_user_id AND ch.verb_id=p.verb_id AND ch.tense=p.tense AND ch.result IS NOT NULL ORDER BY ch.created_at DESC LIMIT 1) c ON true
    WHERE p.auth_user_id=actor AND p.last_answered_at IS NOT NULL AND sitov_verb_private.verb_allowed(actor,p.verb_id) AND sitov_verb_private.level_allowed(actor,c.context_level)
   ), latest AS ($fragment$);
   body:=replace(body,'l.is_active AND (staff OR EXISTS','l.is_active AND (sitov_verb_private.level_allowed(actor,l.code) OR staff OR EXISTS');
   EXECUTE body;
  END IF;
 END IF;
 FOREACH signature IN ARRAY ARRAY['learning_private.reset_student_level(uuid,text)','learning_reset_private.finish_reset(uuid)'] LOOP
  IF to_regprocedure(signature) IS NULL THEN CONTINUE; END IF;
