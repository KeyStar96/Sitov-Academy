-- Verb IDs are stable across source corrections and redeploys; one unit per verb
-- reuses the existing teacher unit-selection model and its exact-level grants.
CREATE TABLE IF NOT EXISTS public.sitov_verb_catalog (
 id text PRIMARY KEY CHECK(id LIKE 'sitov-verb-%'),
 unit_id uuid NOT NULL UNIQUE REFERENCES public.learning_units(id),
 level text NOT NULL REFERENCES public.learning_levels(code)
);
CREATE TABLE IF NOT EXISTS public.sitov_verb_box (
 auth_user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 verb_id text NOT NULL REFERENCES public.sitov_verb_catalog(id),
 selected boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 PRIMARY KEY(auth_user_id,verb_id)
);
CREATE TABLE IF NOT EXISTS public.sitov_verb_progress (
 auth_user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 verb_id text NOT NULL REFERENCES public.sitov_verb_catalog(id),
 tense text NOT NULL CHECK(tense IN('present','perfect','past')),
 box integer NOT NULL DEFAULT 1 CHECK(box BETWEEN 1 AND 7),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts>=0),
 correct integer NOT NULL DEFAULT 0 CHECK(correct BETWEEN 0 AND attempts),
 lapses integer NOT NULL DEFAULT 0 CHECK(lapses>=0),
 next_review_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 last_answered_at timestamptz,
 PRIMARY KEY(auth_user_id,verb_id,tense)
);
CREATE TABLE IF NOT EXISTS public.sitov_verb_challenges (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 auth_user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
 verb_id text NOT NULL REFERENCES public.sitov_verb_catalog(id),
 context_level text NOT NULL REFERENCES public.learning_levels(code),
 tense text NOT NULL CHECK(tense IN('present','perfect','past')),
 expected jsonb NOT NULL CHECK(jsonb_typeof(expected)='array'),
 solution text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
 expires_at timestamptz NOT NULL DEFAULT clock_timestamp()+interval '2 hours',
 answer jsonb,
 result jsonb
);
CREATE INDEX IF NOT EXISTS sitov_verb_challenge_owner_idx ON public.sitov_verb_challenges(auth_user_id,created_at);

CREATE OR REPLACE FUNCTION sitov_verb_private.level_allowed(p_user uuid,p_level text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT EXISTS(SELECT 1 FROM public.profiles p WHERE p.id=p_user AND p_level IN('A1.1','A1.2','A2.1','A2.2','B1.1','B1.2','B2','C1') AND (p.role IN('teacher','admin') OR (
  (p_level IN('A1.1','A1.2','A2.1','A2.2','B1.1','B1.2') AND EXISTS(SELECT 1 FROM public.student_level_access a WHERE a.auth_user_id=p_user AND a.level=p_level)
   OR p_level IN('B2','C1') AND EXISTS(SELECT 1 FROM public.learning_trainer_grants g WHERE g.auth_user_id=p_user AND g.level=p_level AND g.trainer='verbs' AND g.enabled))
  AND coalesce((SELECT g.enabled FROM public.learning_trainer_grants g WHERE g.auth_user_id=p_user AND g.level=p_level AND g.trainer='verbs'),true)
  AND NOT EXISTS(SELECT 1 FROM public.learning_trainer_grants g WHERE g.auth_user_id=p_user AND g.level=p_level AND g.trainer='verbs' AND g.unit_mode='selected' AND NOT EXISTS(SELECT 1 FROM public.learning_unit_grants u WHERE u.auth_user_id=p_user AND u.level=p_level AND u.trainer='verbs')))));
$$;
CREATE OR REPLACE FUNCTION sitov_verb_private.verb_allowed(p_user uuid,p_verb text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT EXISTS(SELECT 1 FROM public.sitov_verb_catalog c JOIN public.learning_units u ON u.id=c.unit_id WHERE c.id=p_verb AND u.is_active AND u.level=c.level AND u.trainer='verbs'
 AND sitov_verb_private.level_allowed(p_user,c.level) AND (EXISTS(SELECT 1 FROM public.profiles WHERE id=p_user AND role IN('teacher','admin'))
 OR NOT EXISTS(SELECT 1 FROM public.learning_trainer_grants g WHERE g.auth_user_id=p_user AND g.level=c.level AND g.trainer='verbs' AND g.unit_mode='selected')
 OR EXISTS(SELECT 1 FROM public.learning_unit_grants g WHERE g.auth_user_id=p_user AND g.unit_id=c.unit_id AND g.trainer='verbs')));
$$;
-- Keep all pre-existing trainer access semantics; advanced levels are verb-only.
CREATE OR REPLACE FUNCTION trainer_access_private.allowed(p_level text,p_trainer text) RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path='' AS $$
 SELECT CASE WHEN p_trainer='verbs' THEN sitov_verb_private.level_allowed((SELECT auth.uid()),p_level)
 ELSE EXISTS(SELECT 1 FROM public.profiles p WHERE p.id=(SELECT auth.uid()) AND (p.role IN('teacher','admin') OR (
 p.ui_language<>'de' AND p_level IN('A1.1','A1.2','A2.1','A2.2','B1.1','B1.2') AND p_trainer IN('vocabulary','exercises','pronunciation','videos')
 AND EXISTS(SELECT 1 FROM public.student_level_access l WHERE l.auth_user_id=p.id AND l.level=p_level)
 AND coalesce((SELECT a.enabled FROM public.learning_trainer_grants a WHERE a.auth_user_id=p.id AND a.level=p_level AND a.trainer::text=p_trainer),true)))) END;
$$;

